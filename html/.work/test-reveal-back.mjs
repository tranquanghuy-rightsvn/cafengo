import puppeteer from 'puppeteer-core';
import fs from 'node:fs';
import { PNG } from 'pngjs';
import pixelmatch from 'pixelmatch';
const browser = await puppeteer.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true,args:['--no-sandbox','--hide-scrollbars'],defaultViewport:{width:1600,height:1000,deviceScaleFactor:1}});
const page = await browser.newPage();
page.on('pageerror',e=>console.log('PAGEERROR',String(e).slice(0,180)));
await page.goto('http://127.0.0.1:8899/',{waitUntil:'networkidle2'});
await new Promise(r=>setTimeout(r,1200));
await page.evaluate(()=>{const b=document.getElementById('flip-spread').getBoundingClientRect();window.scrollBy(0,b.top+b.height/2-window.innerHeight/2);});
await new Promise(r=>setTimeout(r,1500));
await page.evaluate(()=>{const b=document.getElementById('flip-next');b.click();b.click();b.click();});
await new Promise(r=>setTimeout(r,2400));
const v = await page.evaluate(()=>{
  const t=[...document.querySelectorAll('.leaf.is-flipped')].sort((a,b)=>(+b.style.zIndex||0)-(+a.style.zIndex||0))[0];
  const r=t.querySelector('.leaf__face--back').getBoundingClientRect();
  return {x:r.left+scrollX,y:r.top+scrollY,w:r.width,h:r.height,vx:r.left,vy:r.top};
});
/* outer half of the LEFT page — the sheet leaves this area first when turning back */
const strip = {x:v.x+20, y:v.y+40, width:Math.round(v.w*0.45), height:v.h-80};
const oldPage = await page.screenshot({clip:strip, encoding:'binary'});
await page.mouse.move(v.vx+110, v.vy+v.h-110);
await new Promise(r=>setTimeout(r,450));
await page.mouse.down(); await page.mouse.up();
await page.evaluate(async ()=>{ const t0=performance.now(); while(performance.now()-t0 < 5000) await new Promise(r=>requestAnimationFrame(r)); });
const turning = await page.evaluate(()=>!!document.querySelector('.leaf.is-turning'));
const clipNow = await page.evaluate(()=>{const l=document.querySelector('.leaf.is-turning');return l?l.querySelector('.leaf__face--back').style.clipPath.slice(0,62):'-';});
const mid = await page.screenshot({clip:strip, encoding:'binary'});
await new Promise(r=>setTimeout(r,1800));
const landed = await page.screenshot({clip:strip, encoding:'binary'});
const sim=(a,b)=>{const A=PNG.sync.read(a),B=PNG.sync.read(b);const d=new PNG({width:A.width,height:A.height});
  const bad=pixelmatch(A.data,B.data,d.data,A.width,A.height,{threshold:0.12,includeAA:true});
  return ((1-bad/(A.width*A.height))*100).toFixed(2)+'%';};
console.log('still turning when sampled :', turning);
console.log('face clip at that moment   :', clipNow);
console.log('\nouter strip of the LEFT page:');
console.log('  mid-turn vs OLD page :', sim(mid, oldPage));
console.log('  mid-turn vs NEW page :', sim(mid, landed), ' <- should be the high one');
await browser.close();
